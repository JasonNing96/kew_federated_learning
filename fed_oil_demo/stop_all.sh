#!/bin/bash
# 停止所有联邦学习进程

cd "$(dirname "$0")"

echo "=========================================="
echo "停止联邦学习进程"
echo "=========================================="

# 停止客户端
echo "🛑 停止客户端..."
pkill -f "python client.py" && echo "✓ 客户端已停止" || echo "⚠️  无运行中的客户端"

# 停止服务器
echo "🛑 停止服务器..."
